/**
 * In-app alert feedback (owner: alerts): bundled sounds (expo-audio), voice readout (expo-speech),
 * vibration (React Native Vibration) and haptics (expo-haptics).
 *
 * - MAX: looping alarm whose volume ramps from alertVolume * 0.4 to alertVolume over ~20 s, voice
 *   readout (ducking the alarm) repeated up to 3 times, repeating vibration. Runs until stopped.
 * - MEDIUM: one chime at alertVolume + one voice readout + one vibration burst.
 * - LIGHT / follow-up: one soft chime (voice only when the user chose voice-only) + light haptic.
 * - Preferences: alertSoundType (voice_and_sound | voice_only | sound_only), alertVolume,
 *   vibrationEnabled (also covers haptics: nothing vibrates when it is off).
 * Feedback failures never break the visual alert: they are logged (no content) and skipped.
 * Note: expo-audio plays on the media stream (there is no Android audio-usage option), so a muted
 * media volume silences the in-app alarm; the OS notification on the MAX channel uses the alarm
 * stream and stays the reliable audible path.
 */
import { createAudioPlayer, setAudioModeAsync, type AudioPlayer } from 'expo-audio';
import * as Haptics from 'expo-haptics';
import * as Speech from 'expo-speech';
import { Vibration } from 'react-native';

import { createLogger } from '../../core/logger';
import {
  ALARM_RAMP_DURATION_MS,
  ALARM_RAMP_START_FACTOR,
  ALARM_RAMP_STEP_MS,
  CHIME_RELEASE_AFTER_MS,
  IN_APP_MAX_VIBRATION,
  IN_APP_MEDIUM_VIBRATION,
  VOICE_DUCK_FACTOR,
  VOICE_FIRST_DELAY_MS,
  VOICE_MAX_REPEATS,
  VOICE_REPEAT_MS,
} from './constants';
import type { AlertIntensity, AlertSoundType, FeedbackPort, Language } from './types';

const log = createLogger('alerts.feedback');

// Bundled assets (generated by assets/sounds/generate-sounds.js).
const ALARM_SOURCE: number = require('../../../assets/sounds/meeting_alarm.wav');
const CHIME_SOURCE: number = require('../../../assets/sounds/meeting_chime.wav');

export interface FeedbackRequest {
  intensity: AlertIntensity | 'followup';
  soundType: AlertSoundType;
  /** 0..1 */
  volume: number;
  vibrationEnabled: boolean;
  /** Text read aloud (already localized in `language`); null = no voice. */
  voice: { text: string; language: Language } | null;
}

export interface FeedbackHandle {
  stop(): void;
}

export function speechLanguageTag(language: Language): string {
  return language === 'es' ? 'es-ES' : 'en-US';
}

function clampVolume(value: number): number {
  return Number.isFinite(value) ? Math.min(1, Math.max(0, value)) : 0;
}

function safely(what: string, fn: () => void): void {
  try {
    fn();
  } catch (error) {
    log.warn(`${what} failed`, error);
  }
}

async function safelyAsync(what: string, fn: () => Promise<unknown>): Promise<void> {
  try {
    await fn();
  } catch (error) {
    log.warn(`${what} failed`, error);
  }
}

function releasePlayer(player: AudioPlayer | null): void {
  if (!player) return;
  safely('audio release', () => {
    player.pause();
    player.remove();
  });
}

class FeedbackSession implements FeedbackHandle {
  private stopped = false;
  private player: AudioPlayer | null = null;
  private timers: ReturnType<typeof setTimeout>[] = [];
  private rampTimer: ReturnType<typeof setInterval> | null = null;
  private vibrating = false;
  private speaking = false;
  private ducked = false;
  private level = 0;

  constructor(
    private readonly request: FeedbackRequest,
    private readonly onStopped: (session: FeedbackSession) => void,
  ) {}

  start(): void {
    const { intensity } = this.request;
    if (intensity === 'max') this.startMax();
    else if (intensity === 'medium') this.startMedium();
    else this.startLight();
  }

  stop(): void {
    if (this.stopped) return;
    this.stopped = true;
    this.timers.forEach((timer) => clearTimeout(timer));
    this.timers = [];
    if (this.rampTimer) clearInterval(this.rampTimer);
    this.rampTimer = null;
    if (this.speaking) void safelyAsync('speech stop', () => Speech.stop());
    if (this.vibrating) safely('vibration cancel', () => Vibration.cancel());
    releasePlayer(this.player);
    this.player = null;
    this.onStopped(this);
  }

  private get wantsSound(): boolean {
    return this.request.soundType !== 'voice_only' && clampVolume(this.request.volume) > 0;
  }

  private get wantsVoice(): boolean {
    return this.request.soundType !== 'sound_only' && this.request.voice !== null;
  }

  private later(ms: number, fn: () => void): void {
    this.timers.push(
      setTimeout(() => {
        if (!this.stopped) fn();
      }, ms),
    );
  }

  private async prepareAudio(mode: { playsInSilentMode: boolean; interruptionMode: 'doNotMix' | 'duckOthers' }): Promise<void> {
    await safelyAsync('audio mode', () =>
      setAudioModeAsync({
        playsInSilentMode: mode.playsInSilentMode,
        interruptionMode: mode.interruptionMode,
        shouldPlayInBackground: false,
        allowsRecording: false,
        shouldRouteThroughEarpiece: false,
      }),
    );
  }

  private speak(onFinished?: () => void): void {
    const voice = this.request.voice;
    if (!voice || this.stopped) return;
    const done = () => {
      this.speaking = false;
      this.unduck();
      onFinished?.();
    };
    this.duck();
    this.speaking = true;
    safely('speech', () =>
      Speech.speak(voice.text, {
        language: speechLanguageTag(voice.language),
        rate: 0.95,
        pitch: 1.0,
        volume: Math.max(0.6, clampVolume(this.request.volume)),
        onDone: done,
        onStopped: done,
        onError: (error: Error) => {
          log.warn('speech error', error);
          done();
        },
      }),
    );
  }

  private duck(): void {
    this.ducked = true;
    const player = this.player;
    if (player) safely('audio duck', () => (player.volume = this.level * VOICE_DUCK_FACTOR));
  }

  private unduck(): void {
    this.ducked = false;
    const player = this.player;
    if (player && !this.stopped) safely('audio unduck', () => (player.volume = this.level));
  }

  private vibrate(pattern: readonly number[], repeat: boolean): void {
    if (!this.request.vibrationEnabled) return;
    this.vibrating = true;
    safely('vibration', () => Vibration.vibrate([...pattern], repeat));
  }

  /** Haptic tap; skipped when the user turned vibration off. */
  private haptic(kind: 'warning' | 'light'): void {
    if (!this.request.vibrationEnabled) return;
    void safelyAsync('haptics', () =>
      kind === 'warning'
        ? Haptics.notificationAsync(Haptics.NotificationFeedbackType.Warning)
        : Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light),
    );
  }

  private startMax(): void {
    const target = clampVolume(this.request.volume);
    const startLevel = target * ALARM_RAMP_START_FACTOR;
    this.vibrate(IN_APP_MAX_VIBRATION, true);
    this.haptic('warning');

    void (async () => {
      await this.prepareAudio({ playsInSilentMode: true, interruptionMode: 'doNotMix' });
      if (this.stopped) return;
      if (this.wantsSound) {
        safely('alarm start', () => {
          const player = createAudioPlayer(ALARM_SOURCE);
          player.loop = true;
          this.level = startLevel;
          player.volume = startLevel;
          player.play();
          this.player = player;
        });
        const startedAt = Date.now();
        this.rampTimer = setInterval(() => {
          const progress = Math.min(1, (Date.now() - startedAt) / ALARM_RAMP_DURATION_MS);
          this.level = startLevel + (target - startLevel) * progress;
          const player = this.player;
          if (player && !this.ducked) safely('alarm ramp', () => (player.volume = this.level));
          if (progress >= 1 && this.rampTimer) {
            clearInterval(this.rampTimer);
            this.rampTimer = null;
          }
        }, ALARM_RAMP_STEP_MS);
      }
      if (this.wantsVoice) {
        let spoken = 0;
        const readOut = () => {
          spoken += 1;
          this.speak(() => {
            if (spoken < VOICE_MAX_REPEATS) this.later(VOICE_REPEAT_MS, readOut);
          });
        };
        this.later(this.wantsSound ? VOICE_FIRST_DELAY_MS : 0, readOut);
      }
    })();
  }

  private playChimeOnce(volume: number, playsInSilentMode: boolean, then?: () => void): void {
    void (async () => {
      await this.prepareAudio({ playsInSilentMode, interruptionMode: 'duckOthers' });
      if (this.stopped) return;
      safely('chime', () => {
        const player = createAudioPlayer(CHIME_SOURCE);
        player.loop = false;
        this.level = volume;
        player.volume = volume;
        player.play();
        this.player = player;
      });
      this.later(CHIME_RELEASE_AFTER_MS, () => {
        releasePlayer(this.player);
        this.player = null;
      });
      then?.();
    })();
  }

  private startMedium(): void {
    this.vibrate(IN_APP_MEDIUM_VIBRATION, false);
    this.haptic('warning');
    const speakLater = () => {
      if (this.wantsVoice) this.later(this.wantsSound ? VOICE_FIRST_DELAY_MS : 0, () => this.speak());
    };
    if (this.wantsSound) this.playChimeOnce(clampVolume(this.request.volume), true, speakLater);
    else speakLater();
  }

  private startLight(): void {
    this.haptic('light');
    if (this.wantsSound) this.playChimeOnce(clampVolume(this.request.volume) * 0.6, false);
    else if (this.request.soundType === 'voice_only') this.speak();
  }
}

class AlertFeedbackController implements FeedbackPort {
  private readonly sessions = new Set<FeedbackSession>();

  /** Starts feedback for one visible alert; call handle.stop() when it is handled or unmounted. */
  start(request: FeedbackRequest): FeedbackHandle {
    const session = new FeedbackSession(request, (stopped) => this.sessions.delete(stopped));
    this.sessions.add(session);
    session.start();
    return session;
  }

  stopAll(): void {
    [...this.sessions].forEach((session) => session.stop());
  }
}

export const alertFeedback = new AlertFeedbackController();
