// Expo config plugin (Android): keep the app's data out of cloud backups AND device-to-device
// transfers.
//
// `android.allowBackup: false` (app.config.js) turns off Auto Backup, but for apps that target
// Android 12+ (API 31+) some manufacturers still copy the app's data during a phone-to-phone
// migration ("device-to-device transfer") unless android:dataExtractionRules excludes it. The app's
// storage holds the Firebase session (refresh token), the meeting cache, the outbox and the
// assistant thread, so a new phone must never start signed in without the user.
//
// This plugin writes res/xml/mg_data_extraction_rules.xml, which excludes every storage domain from
// <cloud-backup> and <device-transfer>, and points <application android:dataExtractionRules> at it.
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const RULES_NAME = 'mg_data_extraction_rules';
const RULES_REF = `@xml/${RULES_NAME}`;

// Credential-protected and device-protected storage (see <data-extraction-rules> in the Android docs).
const DOMAINS = [
  'root',
  'file',
  'database',
  'sharedpref',
  'external',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
];

function excludeAll(indent) {
  return DOMAINS.map((domain) => `${indent}<exclude domain="${domain}" path="." />`).join('\n');
}

const DATA_EXTRACTION_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withNoDeviceTransfer.js. No app data in cloud backups or device-to-device transfers. -->
<data-extraction-rules>
  <cloud-backup>
${excludeAll('    ')}
  </cloud-backup>
  <device-transfer>
${excludeAll('    ')}
  </device-transfer>
</data-extraction-rules>
`;

/** Points <application> at the rules (and keeps backups off). Exported for tests. */
function setDataExtractionRules(manifest) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  application.$['android:allowBackup'] = 'false';
  application.$['android:dataExtractionRules'] = RULES_REF;
  // Pre-Android 12 rules: irrelevant with allowBackup=false; drop another plugin's file reference.
  delete application.$['android:fullBackupContent'];
  return manifest;
}

function withNoDeviceTransfer(config) {
  config = withAndroidManifest(config, (next) => {
    next.modResults = setDataExtractionRules(next.modResults);
    return next;
  });
  return withDangerousMod(config, [
    'android',
    async (next) => {
      const xmlDir = path.join(next.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      await fs.promises.mkdir(xmlDir, { recursive: true });
      await fs.promises.writeFile(path.join(xmlDir, `${RULES_NAME}.xml`), DATA_EXTRACTION_RULES_XML, 'utf8');
      return next;
    },
  ]);
}

module.exports = withNoDeviceTransfer;
module.exports.DATA_EXTRACTION_RULES_XML = DATA_EXTRACTION_RULES_XML;
module.exports.setDataExtractionRules = setDataExtractionRules;
